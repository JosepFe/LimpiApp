// Writes the prototype's component CSS and icon sprite into the app (the visual contract). Usage: npm run styles
//   src/styles/prototype.css  every rule of the prototype <style> except the token blocks (src/styles/_tokens.scss)
//                             and the demo chrome (.demo-bar, body.bare)
//   public/icons.svg          the <symbol> sprite, used as <svg><use href="icons.svg#i-today"/></svg>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { frontendDir, prototypePath } from './prototype.mjs';

/** Splits CSS into top-level chunks: comments, `selector{…}` rules and `@media…{…}` blocks. */
function chunks(css) {
  const out = [];
  let i = 0;
  while (i < css.length) {
    if (/\s/.test(css[i])) { i++; continue; }
    if (css.startsWith('/*', i)) {
      const end = css.indexOf('*/', i) + 2;
      out.push(css.slice(i, end));
      i = end;
      continue;
    }
    const open = css.indexOf('{', i);
    let depth = 0;
    let j = open;
    for (; j < css.length; j++) {
      if (css[j] === '{') depth++;
      else if (css[j] === '}' && --depth === 0) break;
    }
    out.push(css.slice(i, j + 1));
    i = j + 1;
  }
  return out;
}

const DEMO = /\.demo-bar|body\.bare|body:not\(\.bare\)|^:root\s*\{|^:root\[data-theme="dark"\]\s*\{/;

/** Keeps the app rules: drops comments, token blocks and demo chrome (also inside @media). */
export function appCss(css) {
  return chunks(css)
    .filter((c) => !c.startsWith('/*'))
    .map((c) => {
      if (!c.startsWith('@media')) return DEMO.test(c) ? '' : c;
      const head = c.slice(0, c.indexOf('{') + 1);
      const inner = chunks(c.slice(head.length, -1)).filter((r) => !r.startsWith('/*') && !DEMO.test(r));
      return inner.length ? `${head}\n  ${inner.join('\n  ')}\n}` : '';
    })
    .filter(Boolean)
    .join('\n');
}

export function sprite(html) {
  const symbols = [...html.matchAll(/<symbol[\s\S]*?<\/symbol>/g)].map((m) => m[0]);
  return `<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\n${symbols.join('\n')}\n</svg>\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const html = readFileSync(prototypePath(), 'utf8');
  const style = html.match(/<style>([\s\S]*?)<\/style>/)[1];
  const header = '/* Generated by scripts/sync-styles.mjs from the prototype <style>. Do not edit by hand: a design change goes to the prototype first. */\n';
  writeFileSync(join(frontendDir, 'src/styles/prototype.css'), header + appCss(style) + '\n');
  writeFileSync(join(frontendDir, 'public/icons.svg'), sprite(html));
  console.log('src/styles/prototype.css and public/icons.svg written');
}
