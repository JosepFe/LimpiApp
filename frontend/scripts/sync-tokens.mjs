// Writes src/styles/_tokens.scss from the prototype's :root blocks (the visual contract). Usage: npm run tokens
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { frontendDir, prototypePath, prototypeTokens } from './prototype.mjs';

const { light, dark } = prototypeTokens();
const body = (tokens) => tokens.map(([name, value]) => `  ${name}: ${value};`).join('\n');
const source = prototypePath().endsWith('e2e/prototype.html') ? 'e2e/prototype.html' : 'Design/prototype.html (vault)';
const out = `// Generated by scripts/sync-tokens.mjs from the :root blocks of ${source}.
// Do not edit by hand: a design change goes to the prototype first.
:root {
${body(light)}
}

:root[data-theme='dark'] {
${body(dark)}
}
`;
writeFileSync(join(frontendDir, 'src/styles/_tokens.scss'), out);
console.log(`${light.length} light and ${dark.length} dark tokens written to src/styles/_tokens.scss`);
